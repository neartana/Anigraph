import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { launchChrome, sleep } from '../../../qa/cdp.mjs';

const out = import.meta.dirname;
const browser = await launchChrome();
const page = await browser.newPage();
const tiersOnly = process.argv.includes('--tiers');
const manifest = tiersOnly ? JSON.parse(await fs.readFile(path.join(out,'provenance.json'),'utf8')) : { captured: new Date().toISOString(), source: 'http://127.0.0.1:5174/', profile: 'https://anilist.co/user/Neartana/', viewport: { width: 1440, height: 900 }, screenshots: [] };
const click = selector => page.evaluate(s => document.querySelector(s).click(), selector);
const frame = (selector, offset = 28) => page.evaluate((s, o) => { const target=document.querySelector(s);window.scrollTo(0,Math.max(0,scrollY+target.getBoundingClientRect().top-o)); }, selector, offset);
async function capture(name, description) {
  await page.mouse('mousePressed', 20, 20);
  await page.mouse('mouseReleased', 20, 20);
  await page.waitFor(() => document.querySelector('#toast')?.hidden !== false, { timeout: 6000 });
  await page.evaluate(() => document.fonts.ready);
  await page.waitFor(() => [...document.querySelectorAll('img')].filter(e => { const r=e.getBoundingClientRect();return r.top<innerHeight&&r.bottom>0; }).every(e=>e.complete), { timeout: 30000 });
  await sleep(200);
  const { data } = await page.cdp.send('Page.captureScreenshot', { format: 'jpeg', quality: 92 }, page.sessionId);
  await fs.writeFile(path.join(out,name+'.jpg'),Buffer.from(data,'base64'));
  manifest.screenshots=manifest.screenshots.filter(item=>item.file!==name+'.jpg');
  manifest.screenshots.push({ file: name+'.jpg', captured: new Date().toISOString(), width: 1440, height: 900, description, url: await page.url(), title: await page.title() });
  await fs.writeFile(path.join(out,'provenance.json'),JSON.stringify(manifest,null,2)+'\n');
  console.log('Captured '+name);
}
try {
  await page.setReducedMotion(true);
  await page.setViewport(manifest.viewport);
  await page.cdp.send('Emulation.setTimezoneOverride',{timezoneId:'Asia/Jakarta'},page.sessionId);
  await page.goto(manifest.source);
  if (!tiersOnly) {
  await page.evaluate(() => { document.querySelector('#statsUsername').value='Neartana'; document.querySelector('#statsForm').requestSubmit(); });
  await page.waitForSelector('.title-chart-row',{timeout:60000});
  await page.evaluate(() => { const target=document.querySelector('.profile-block');window.scrollTo(0,Math.max(0,scrollY+target.getBoundingClientRect().top-40)); });
  await capture('stats','Current Stats view, public AniList profile Neartana; real source totals and charts.');
  await click('[data-view-target="library"]');
  await page.waitForSelector('.library-card',{timeout:60000});
  await frame('.library-filters');
  await capture('library','Current anime library for public AniList profile Neartana, with source artwork.');
  await click('[data-library-mode="pick"]');
  await page.waitForSelector('[data-action="pick-title"]');
  await click('[data-action="pick-title"]');
  await page.waitForSelector('.picked-title');
  await frame('.picker-panel');
  await capture('pick','Real random result generated by Pick for Me from Neartana’s public anime library.');
  await click('[data-library-mode="discover"]');
  await page.waitForSelector('.catalog-grid',{timeout:60000});
  await frame('.library-head');
  await capture('discover','Live recommendations generated from Neartana’s public ratings, excluding titles in their library.');
  await click('[data-view-target="radar"]');
  await page.waitFor(() => document.querySelector('#viewRadar[aria-busy="false"] .radar-episode'),{timeout:60000});
  await page.evaluate(() => window.scrollTo(0,0));
  await capture('airing','Live airing schedule from AniList, displayed in Asia/Jakarta local time.');
  }
  await click('[data-view-target="tiers"]');
  await page.evaluate(() => { const input=document.querySelector('#tierSearchInput');input.value='Frieren';input.dispatchEvent(new Event('input',{bubbles:true})); });
  await page.waitForSelector('.media-card[data-media-id="154587"]',{timeout:30000});
  await click('.media-card[data-media-id="154587"]');
  await page.waitForSelector('.char-card',{timeout:60000}).catch(async error=>{console.log(await page.evaluate(()=>document.querySelector('#viewTiers').innerText));throw error;});
  const chars=await page.evaluate(() => [...document.querySelectorAll('.char-card')].slice(0,12).map(e=>e.dataset.charId));
  for (let i=0;i<chars.length;i++) {
    await click('[data-action="open-move"][data-char-id="'+chars[i]+'"]');
    await click('[data-action="move-char"][data-target-row="'+['S','A','B'][Math.floor(i/4)]+'"]');
  }
  await frame('.board-head');
  await capture('tiers','Current Tier Lists UI using live Frieren characters from AniList. Rankings are a newly created demonstration board in an isolated browser, not the user’s saved rankings.');
  assert.equal(page.events.exceptions.length,0,'No uncaught browser exceptions during capture');
  manifest.chrome=browser.version;
  await fs.writeFile(path.join(out,'provenance.json'),JSON.stringify(manifest,null,2)+'\n');
} finally { await browser.close(); }
